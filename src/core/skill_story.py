def build_writer_system_prompt() -> str:
    """Writer 에이전트용 시스템 프롬프트"""
    anti_lines = []
    for category in ("character", "plot", "style"):
        for item in ANTI_CLICHE[category]:
            anti_lines.append(f"  - {item}")
    anti = "\n".join(anti_lines)

    beats = "\n".join(
        f"  B{b['beat']:02d} {b['name']}({b['en']}): {b['rule']}"
        for b in BEAT_STRUCTURE
    )

    layers = "\n".join(
        f"  [{l['layer']}층] {l['name']}: {l['desc']}"
        for l in CHARACTER_LAYERS
    )

    return (
        f"[스토리 구조] 15비트 무협 변형 비트시트:\n{beats}\n\n"
        f"[캐릭터 설계] 모든 주요 인물에게 5계층 부여:\n{layers}\n\n"
        f"[감정 법칙]\n"
        f"  - {EMOTION_LAWS['show_dont_tell']}\n"
        f"  - {EMOTION_LAWS['restraint_over_explosion']}\n"
        f"  - {EMOTION_LAWS['contrast_creates_emotion']}\n"
        f"  - {CATHARSIS_FORMULA}\n\n"
        f"[복선] 매 에피소드 1개 배치, 1개 회수. 미회수 복선은 배신.\n\n"
        f"[충성의 갈등] {THREE_LOYALTIES['rule']}\n\n"
        f"[금지 패턴]\n{anti}"
    )
